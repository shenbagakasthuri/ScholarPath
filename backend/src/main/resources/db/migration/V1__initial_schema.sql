CREATE TABLE `scholarship_matches` (
    `id` BIGINT NOT NULL AUTO_INCREMENT,
    `student_profile_id` BIGINT NOT NULL,
    `scholarship_id` BIGINT NOT NULL,
    `match_score` DECIMAL(5,2) NOT NULL,
    `eligibility_status` VARCHAR(50) NOT NULL,
    `matched_criteria_count` INT NOT NULL DEFAULT 0,
    `total_mandatory_criteria_count` INT NOT NULL DEFAULT 0,
    `missing_criteria_json` JSON,
    `verified_criteria_json` JSON,
    `unverified_criteria_json` JSON,
    `match_explanation` TEXT,
    `ai_generated_explanation` TEXT,
    `is_notified` BOOLEAN NOT NULL DEFAULT FALSE,
    `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    FOREIGN KEY (`student_profile_id`) REFERENCES `student_profiles`(`id`) ON DELETE CASCADE,
    FOREIGN KEY (`scholarship_id`) REFERENCES `scholarships`(`id`) ON DELETE CASCADE,
    UNIQUE KEY `uk_scholarship_matches_student_scholarship` (`student_profile_id`, `scholarship_id`),
    INDEX `idx_scholarship_matches_student_profile_id` (`student_profile_id`),
    INDEX `idx_scholarship_matches_scholarship_id` (`scholarship_id`),
    INDEX `idx_scholarship_matches_eligibility_status` (`eligibility_status`),
    INDEX `idx_scholarship_matches_match_score` (`match_score`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

